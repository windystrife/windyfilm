#!/usr/bin/env python3
"""mk_logtab.py OUT.h - tables for the log output modes of wf_logout_ref.c (WindyFilm).

Input : the camera's JPEG-bound YCbCr (BT.601 full range, display-referred sRGB / Rec.709 primaries).
Output: the same picture re-encoded as camera log (normalized code value -> full-range 8-bit), so a
        manufacturer / creative LUT for that log + gamut can be applied in post.

  mode 1  S-Log3        / S-Gamut3.Cine   (Sony, "Technical Summary for S-Gamut3.Cine/S-Log3")
  mode 2  V-Log         / V-Gamut         (Panasonic, "V-Log/V-Gamut Reference manual")
  mode 3  ARRI LogC3 EI800 / ARRI Wide Gamut 3 (ARRI, "ALEXA Log C Curve - Usage in VFX", SUP 3.x)
  mode 4  Canon Log 2   / Cinema Gamut    (Canon, input transform 202007 = Canon Log v1.2; Cinema Gamut: EOS C500
  mode 5  Canon Log 3   / Cinema Gamut     firmware notes; owner 2026-11-13)

Tables:
  wf_dec[1024]     sRGB code value v = i/4 (0..255.75) -> linear light, Q14 (16384 = 1.0), sRGB EOTF
  wf_lmat[5][9]    linear Rec.709 RGB -> linear target-gamut RGB, Q14, rows sum to 16384 (white kept)
  wf_lenc[5][4097] linear Q12 index (0..4096 = 0..1.0) -> log code value * 256 (Q8, 0..65280)
Pure stdlib, deterministic; build.sh runs it and wf_logout_ref.c includes the result.
"""
import math
import sys

Q = 16384          # linear Q14
NENC = 4097        # encode table: linear Q12 index


def srgb_eotf(v):
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def slog3(x):
    if x >= 0.01125000:
        return (420.0 + math.log10((x + 0.01) / (0.18 + 0.01)) * 261.5) / 1023.0
    return (x * (171.2102946929 - 95.0) / 0.01125000 + 95.0) / 1023.0


def vlog(x):
    if x < 0.01:
        return 5.6 * x + 0.125
    return 0.241514 * math.log10(x + 0.00873) + 0.598206


def logc3_ei800(x):
    cut, a, b, c, d, e, f = 0.010591, 5.555556, 0.052272, 0.247190, 0.385537, 5.367655, 0.092809
    return c * math.log10(a * x + b) + d if x > cut else e * x + f


def clog2(x):
    """Canon Log 2 v1.2 (Canon, input transform 202007, as colour-science log_encoding_CanonLog2): reflectance x
    (18 % grey = 0.18) / 0.9, normalised code value (legal range already in the constants): 0.18 -> 0.3983"""
    x = x / 0.9
    if x < 0:
        return -(0.24136077 * math.log10(-x * 87.09937546 + 1) - 0.092864125)
    return 0.24136077 * math.log10(x * 87.09937546 + 1) + 0.092864125


def clog3(x):
    """Canon Log 3 v1.2 (same source): linear segment |x / 0.9| <= 0.014, 0.18 -> 0.3434"""
    x = x / 0.9
    if x < -0.014:
        return -0.36726845 * math.log10(-x * 14.98325 + 1) + 0.12783901
    if x <= 0.014:
        return 1.9754798 * x + 0.12512219
    return 0.36726845 * math.log10(x * 14.98325 + 1) + 0.12240537


def npm(prim, white):
    """normalized primary matrix RGB -> XYZ from xy chromaticities"""
    def xyz(xy):
        x, y = xy
        return [x / y, 1.0, (1 - x - y) / y]
    P = [xyz(p) for p in prim]                 # columns
    M = [[P[c][r] for c in range(3)] for r in range(3)]
    W = xyz(white)
    S = solve(M, W)
    return [[M[r][c] * S[c] for c in range(3)] for r in range(3)]


def solve(M, v):
    inv = inverse(M)
    return [sum(inv[r][c] * v[c] for c in range(3)) for r in range(3)]


def inverse(m):
    a, b, c = m[0]; d, e, f = m[1]; g, h, i = m[2]
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return [[(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
            [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
            [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det]]


def mul(A, B):
    return [[sum(A[r][k] * B[k][c] for k in range(3)) for c in range(3)] for r in range(3)]


D65 = (0.3127, 0.3290)
REC709 = [(0.640, 0.330), (0.300, 0.600), (0.150, 0.060)]
GAMUTS = [
    ("S-Gamut3.Cine", [(0.766, 0.275), (0.225, 0.800), (0.089, -0.087)]),
    ("V-Gamut",       [(0.730, 0.280), (0.165, 0.840), (0.100, -0.030)]),
    ("ARRI Wide Gamut 3", [(0.6840, 0.3130), (0.2210, 0.8480), (0.0861, -0.1020)]),
    ("Cinema Gamut", [(0.7400, 0.2700), (0.1700, 1.1400), (0.0800, -0.1000)]),
    ("Cinema Gamut", [(0.7400, 0.2700), (0.1700, 1.1400), (0.0800, -0.1000)]),
]
CURVES = [("S-Log3", slog3), ("V-Log", vlog), ("LogC3 EI800", logc3_ei800), ("Canon Log 2", clog2), ("Canon Log 3", clog3)]
assert len(GAMUTS) == len(CURVES) == 5


def qmat(M):
    """Q14 integer matrix whose rows sum exactly to 16384 (rounding error put on the diagonal)"""
    out = []
    for r in range(3):
        row = [int(round(M[r][c] * Q)) for c in range(3)]
        row[r] += Q - sum(row)
        out += row
    return out


def main():
    lines = ["/* generated by mk_logtab.py - do not edit */", "#include <stdint.h>", ""]
    dec = [int(round(srgb_eotf(min(i / 4.0, 255.0) / 255.0) * Q)) for i in range(1024)]
    lines.append("static const uint16_t wf_dec[1024] = {")
    for i in range(0, 1024, 16):
        lines.append("  " + ",".join(str(v) for v in dec[i:i + 16]) + ",")
    lines.append("};")
    to_xyz = npm(REC709, D65)
    lines.append("static const int32_t wf_lmat[%d][9] = {" % len(GAMUTS))
    for name, prim in GAMUTS:
        M = mul(inverse(npm(prim, D65)), to_xyz)
        q = qmat(M)
        assert all(v >= 0 for v in q), (name, q)          # no negative terms: output stays in 0..1
        lines.append("  { %s },  /* Rec.709 -> %s: %s */" % (", ".join(str(v) for v in q), name,
                     " ".join("%.5f" % M[r][c] for r in range(3) for c in range(3))))
    lines.append("};")
    lines.append("const uint16_t wf_lenc[%d][%d] = {" % (len(CURVES), NENC))           # extern: wf_loglut.c (WF_LL_EXTERN_ENC)
    for name, f in CURVES:
        enc = [int(round(min(max(f(i / (NENC - 1.0)), 0.0), 1.0) * 255.0 * 256.0)) for i in range(NENC)]
        lines.append("  { /* %s: 0 -> %.4f, 0.18 -> %.4f, 1.0 -> %.4f */" % (name, f(0.0), f(0.18), f(1.0)))
        for i in range(0, NENC, 16):
            lines.append("    " + ",".join(str(v) for v in enc[i:i + 16]) + ",")
        lines.append("  },")
    lines.append("};")
    open(sys.argv[1], "w", newline="\n").write("\n".join(lines) + "\n")
    for name, f in CURVES:
        print("  %-12s black %.4f  18%% grey %.4f  white(1.0) %.4f" % (name, f(0), f(0.18), f(1.0)))


main()
