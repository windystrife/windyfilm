#!/usr/bin/env python3
"""wf_checksyms.py CARD.sym MODULE.mo MODNAME [--tcc-syms OUT.c] - WindyFilm symbol check (WindyStrife's own tool).

Checks a linked module (ld -r output after objcopy --keep-global-symbols) against the camera's ML core symbol file
(the card's .sym, "<hex address> <name>" per line):
  - every GLOBAL undefined symbol is exported by the core (else TCC on the camera fails with "undefined symbol");
  - the only GLOBAL definitions are ML's __module_*_<MODNAME> tables (no name can clash with the core or another module);
  - every relocation type is one ML's TCC loader handles (ARM: ABS32, REL32, CALL, JUMP24, PC24, PLT32, V4BX,
    MOVW_ABS_NC, MOVT_ABS); no .ARM.exidx / .ARM.extab (unwind tables need symbols the core does not have);
  - __module_info_<MODNAME> and __module_strings_<MODNAME> exist.
--tcc-syms OUT.c writes the core symbol table for tools/tcc_link.c: one dummy object per imported symbol.
Uses arm-none-eabi-readelf. Exit status 0 = all checks passed."""
import subprocess, sys

OK_RELOCS = {"R_ARM_ABS32", "R_ARM_REL32", "R_ARM_CALL", "R_ARM_JUMP24", "R_ARM_PC24", "R_ARM_PLT32", "R_ARM_V4BX",
             "R_ARM_MOVW_ABS_NC", "R_ARM_MOVT_ABS"}


def readelf(*args):
    return subprocess.run(["arm-none-eabi-readelf"] + list(args), check=True, capture_output=True, text=True).stdout


def main(argv):
    if len(argv) < 4:
        sys.exit(__doc__)
    symf, mo, mod = argv[1], argv[2], argv[3]
    out_c = argv[argv.index("--tcc-syms") + 1] if "--tcc-syms" in argv else None
    core = set()
    for line in open(symf, encoding="ascii", errors="replace"):
        p = line.split()
        if len(p) >= 2:
            core.add(p[1])
    und, glob, errs = set(), [], []
    for line in readelf("-sW", mo).splitlines():
        p = line.split()
        if len(p) < 8 or not p[0].endswith(":"):
            continue
        bind, ndx, name = p[4], p[6], p[7]
        if bind not in ("GLOBAL", "WEAK"):
            continue
        if ndx == "UND":
            und.add(name)
        else:
            glob.append(name)
    missing = sorted(s for s in und if s not in core)
    for s in missing:
        errs.append("imported but not in %s: %s" % (symf, s))
    want = "_" + mod
    for s in glob:
        if not (s.startswith("__module_") and s.endswith(want)):
            errs.append("global definition other than __module_*%s: %s" % (want, s))
        if s in core:
            errs.append("global definition clashes with the core: %s" % s)
    for t in ("__module_info" + want, "__module_strings" + want):
        if t not in glob:
            errs.append("missing %s" % t)
    rel = {}
    for line in readelf("-rW", mo).splitlines():
        p = line.split()
        if len(p) >= 3 and p[2].startswith("R_ARM_"):
            rel[p[2]] = rel.get(p[2], 0) + 1
    for t in sorted(rel):
        if t not in OK_RELOCS:
            errs.append("relocation type the loader does not handle: %s (%d)" % (t, rel[t]))
    secs = readelf("-SW", mo)
    if ".ARM.exidx" in secs or ".ARM.extab" in secs:
        errs.append("unwind tables (.ARM.exidx / .ARM.extab) in the module")
    if out_c:
        with open(out_c, "w") as f:
            f.write("/* generated by tools/wf_checksyms.py: the core symbols %s imports that %s exports */\n" % (mo, symf))
            ok = sorted(s for s in und if s in core)
            for s in ok:
                f.write("char wf_cs_%s[8] __attribute__((aligned(8)));\n" % s)
            f.write("struct core_sym { const char *name; const void *addr; };\n")
            f.write("const struct core_sym wf_core_syms[] = {\n")
            for s in ok:
                f.write('    { "%s", wf_cs_%s },\n' % (s, s))
            f.write("    { 0, 0 }\n};\n")
    print("checksyms %s: %d imports (all in the core: %s), globals %s, relocations %s" % (
        mo, len(und), "yes" if not missing else "NO, %d missing" % len(missing), " ".join(sorted(glob)),
        " ".join("%s:%d" % (t[6:], rel[t]) for t in sorted(rel))))
    for e in errs:
        print("checksyms: " + e)
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
