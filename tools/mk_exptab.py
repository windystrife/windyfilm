#!/usr/bin/env python3
"""mk_exptab.py OUT.h - tables of wf_expsim.c: the sRGB EOTF of every 8-bit code in Q16 (wf_exp_dec[256], 0..65535)
and the gain 2^(k/8) in Q16 for k = 0..7 (wf_exp_g8[8]). Integer-only code on the camera uses them; the host
tests recompute both in floating point and compare."""
import sys

def eotf(y):
    c = y / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

dec = [int(round(eotf(y) * 65535)) for y in range(256)]
g8 = [int(round(65536 * 2 ** (k / 8.0))) for k in range(8)]
assert dec[0] == 0 and dec[255] == 65535 and all(a < b for a, b in zip(dec, dec[1:]))
assert g8[0] == 65536 and all(a < b for a, b in zip(g8, g8[1:]))
with open(sys.argv[1], "w") as f:
    f.write("/* generated by mk_exptab.py: do not edit */\n")
    f.write("static const uint16_t wf_exp_dec[256] = {\n")
    for i in range(0, 256, 16):
        f.write("    " + ", ".join("%d" % v for v in dec[i:i + 16]) + ",\n")
    f.write("};\n")
    f.write("static const uint32_t wf_exp_g8[8] = { " + ", ".join("%d" % v for v in g8) + " };\n")
